export function getTopicUr(slug: string): SeoTopicUr | undefined {
  const base = SEO_TOPICS.find((topic) => topic.slug === slug);
  const ur = UR_BY_SLUG[slug];
  if (!base || !ur) return undefined;
  return {
    slug,
    related: base.related,
    ...ur,
  };
}

export function allTopicUrSlugs(): string[] {
  return SEO_TOPICS.map((topic) => topic.slug).filter((slug) => UR_BY_SLUG[slug]);
}
